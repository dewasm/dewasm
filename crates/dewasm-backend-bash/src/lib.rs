//! Bash backend: translates dewasm IR into a sourceable Bash script plus a bundled runtime of `<p>rt_*`/`<p>mem_*`/`<p>tab_*`/`<p>wasi_*` functions carrying the artifact's own prefix (ADR-62), so two generated scripts sourced into one shell never redefine each other's runtime.
//!
//! Lowering conventions (ADR-11; numeric conventions ADR-2):
//! - i32 is a masked-unsigned value in [0, 2^32); i64 is stored as its signed-64 two's-complement bit pattern (bash arithmetic is signed 64-bit only). Signed/unsigned views are derived inline.
//! - f32/f64 are their bit patterns (u32 / signed-64), computed by the pure-Bash softfloat units (ADR-5/ADR-13); reinterprets and float loads/stores are the identity over the integer paths.
//! - Structured control flow maps to `while :; do ...; break; done` wrappers; `br` becomes `break N`/`continue N` (bash counts only loops, `if` adds no level). Unreferenced labels emit no wrapper.
//! - Functions return values through the globals `R0, R1, ...`; traps set `TRAP_MSG` and propagate status 134 through `|| return $?` chains. Every generated function ends with an explicit `return 0` because a trailing arithmetic statement would leak status 1.
//! - One module instance per generation-time prefix: functions `<p>f<i>`, state `<p>g<i>`/`<p>mem`/`<p>t<i>` (per unified-index-space table), entry points `<p>init`, `<p>invoke`, `<p>global_get`, and — for `Embedded` linkage — the bundled runtime under the same prefix (`<p>rt_trap`, `<p>mem_i32_load`, ...). `TRAP_MSG`, `EXIT_CODE`, the `R0..` result registers and `IMPORTS`/`PROVIDERS` stay global: they are the calling protocol two artifacts must share to link at all (ADR-35/ADR-62). Imported functions resolve from the caller's `IMPORTS` array; other import kinds resolve through `PROVIDERS` + per-kind export maps, with imported globals and imported memory aliased in via `declare -gn` namerefs (ADR-35).
//!
//! Requires bash >= 5 (namerefs, associative arrays).

