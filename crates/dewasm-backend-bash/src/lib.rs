/// Lint for the bash runtime units: every reference a unit body makes to another unit must be declared in its `# requires:` header, and every unit function must end with an explicit `return`/`:` — a trailing arithmetic statement would leak status 1 into the `|| return $?` trap cascade (ADR-11). Static half of the ADR-6 drift defence.
#[cfg(test)]
mod units {
    use super::*;
    use std::collections::BTreeSet;

    use regex::Regex;

    #[test]
    fn all_units_bundle() {
        bundler().bundle_all(0).expect("full bundle resolves");
    }

    #[test]
    fn declared_requires_cover_references() {
        let b = bundler();
        let unit_ids: BTreeSet<&str> = b.units().map(|u| u.id.as_str()).collect();
        let call = Regex::new(r"\b(rt|mem|wasi|tab)_([a-z0-9_]+)").unwrap();

        let mut problems = Vec::new();
        for unit in b.units() {
            let declared: BTreeSet<&str> = unit.requires.iter().map(|s| s.as_str()).collect();
            let code: String = unit
                .body
                .lines()
                .filter(|l| !l.trim_start().starts_with('#'))
                .collect::<Vec<_>>()
                .join("\n");
            for cap in call.captures_iter(&code) {
                let dep = format!("{}/{}", &cap[1], &cap[2]);
                if dep == unit.id || declared.contains(dep.as_str()) {
                    continue;
                }
                if !unit_ids.contains(dep.as_str()) {
                    // Longest-match artifacts (e.g. rt_i32 inside rt_i32_clz) cannot occur because the regex is greedy; anything else unknown is a genuine typo.
                    problems.push(format!("{}: references unknown unit {dep}", unit.id));
                    continue;
                }
                problems.push(format!(
                    "{}: uses {}_{} but does not require {dep}",
                    unit.id, &cap[1], &cap[2]
                ));
            }
        }
        assert!(
            problems.is_empty(),
            "unit dependency drift:\n{}",
            problems.join("\n")
        );
    }

    /// `Embedded` linkage renames the runtime per artifact by rewriting every `rt_`/`mem_`/`wasi_`/`tab_` identifier across the bundle text ([`prefix_runtime_names`], ADR-62), which is sound only while such a name is always code. One inside a string literal would be rewritten too, silently changing program-visible text (a trap message, an errno key, a path); no unit has one today, and this keeps it that way.
    #[test]
    fn no_runtime_name_inside_a_string_literal() {
        let call = Regex::new(r"\b(rt|mem|wasi|tab)_[a-z0-9_]+").unwrap();
        let mut problems = Vec::new();
        for unit in bundler().units() {
            for (n, line) in unit.body.lines().enumerate() {
                for lit in string_literals(line) {
                    if let Some(m) = call.find(&lit) {
                        problems.push(format!(
                            "{}:{}: `{}` inside the string literal {lit}",
                            unit.id,
                            n + 1,
                            m.as_str()
                        ));
                    }
                }
            }
        }
        assert!(
            problems.is_empty(),
            "the Embedded runtime rename would rewrite these string literals:\n{}",
            problems.join("\n")
        );
    }

    /// Every single-line quoted string on `line`, stopping at a `#` comment outside quotes (bash starts a comment only at a word boundary). `\` escapes inside double quotes; single quotes have no escapes at all.
    fn string_literals(line: &str) -> Vec<String> {
        let mut out = Vec::new();
        let chars: Vec<char> = line.chars().collect();
        let mut i = 0;
        while i < chars.len() {
            match chars[i] {
                '#' if i == 0 || chars[i - 1].is_whitespace() => break,
                '\\' => i += 2,
                q @ ('\'' | '"') => {
                    let mut lit = String::new();
                    i += 1;
                    while i < chars.len() && chars[i] != q {
                        if q == '"' && chars[i] == '\\' {
                            i += 1;
                            if i >= chars.len() {
                                break;
                            }
                        }
                        lit.push(chars[i]);
                        i += 1;
                    }
                    out.push(lit);
                    i += 1;
                }
                _ => i += 1,
            }
        }
        out
    }

    /// The rewrite moves definitions and call sites together, leaves anything that is not one of the four runtime scopes alone, and respects identifier boundaries (`__mem_x` is a local, not the `mem_x` unit).
    #[test]
    fn prefixing_moves_whole_names_only() {
        let src = "mem_check() {\n  rt_trap 'x'; local __mem_check=1; wasi_fd_write \"${1}mem\"\n}";
        assert_eq!(
            prefix_runtime_names(src, "alpha_"),
            "alpha_mem_check() {\n  alpha_rt_trap 'x'; local __mem_check=1; alpha_wasi_fd_write \"${1}mem\"\n}"
        );
        assert_eq!(prefix_runtime_names(src, ""), src);
    }

    #[test]
    fn unit_functions_end_with_return() {
        let b = bundler();
        let mut problems = Vec::new();
        for unit in b.units() {
            let lines: Vec<&str> = unit.body.lines().collect();
            for (i, line) in lines.iter().enumerate() {
                if *line != "}" {
                    continue;
                }
                let last = lines[..i]
                    .iter()
                    .rev()
                    .find(|l| !l.trim().is_empty())
                    .map(|l| l.trim())
                    .unwrap_or("");
                if !(last.starts_with("return") || last == ":" || last.ends_with("return $?; }")) {
                    problems.push(format!(
                        "{}: function body ends with `{last}` instead of an explicit return",
                        unit.id
                    ));
                }
            }
        }
        assert!(
            problems.is_empty(),
            "unit functions must end with an explicit return (status discipline):\n{}",
            problems.join("\n")
        );
    }
}
