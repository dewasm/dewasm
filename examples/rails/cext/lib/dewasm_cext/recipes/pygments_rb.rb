# frozen_string_literal: true

require "fileutils"

# `pygments.rb`: a Ruby gem that runs the Pygments it ships (`vendor/pygments-main`) in a
# `python3` child process, `lib/pygments/mentos.py`, and talks to it over a pipe.
# Every call of its API goes through one method, `Pygments::Popen#mentos`.
#
# The converted copy has no child process: CPython is a reactor, `pygments_rb/mentos_host.c`,
# linked against the `cpython-sdk` library build of `examples/apps/setup.sh`, converted to Ruby.
# Its `pyg_init` imports the gem's own `mentos.py` and runs the common lexers once; Wizer runs
# it ahead of time and writes the memory into the module, so the conversion starts with
# Pygments imported.
# A `lib_dewasm/pygments.rb` ahead of the gem's `lib` on the require paths loads the gem's own
# `pygments.rb` and points `Pygments::Popen#mentos` at the reactor; the gem's Ruby and Python are
# unmodified.
# The entry file is the one to shadow: the gem loads `popen.rb` with `require_relative`.
# The interpreter sees the gem directory as `/gem`, with the standard library copied under it.
DewasmCExt::Recipe.register "pygments.rb" do
  checksum "5.0.0", "33b3b0a0da0b4b5d12cedbb2b355b0685bb0a545fb7efb29868945c18148ef6e"

  SDK = File.expand_path("../../../../../apps/cache/cpython-sdk", __dir__)
  SDK_HINT = "run examples/apps/setup.sh (it builds CPython as a library for wasm32-wasip1)"
  PYTHON = "python3.14"
  HOST_SOURCE = File.join(__dir__, "pygments_rb/mentos_host.c")

  def configure
    self.support = false
    self.sources = [HOST_SOURCE]
    self.include_dirs = [File.join(SDK, "include", PYTHON)]
    self.defines = { "_WASI_EMULATED_SIGNAL" => nil, "_WASI_EMULATED_GETPID" => nil,
                     "_WASI_EMULATED_PROCESS_CLOCKS" => nil }
    # The link line of CPython's own `Tools/wasm/wasi` build.
    self.cflags = %w[-z stack-size=16777216 -Wl,--stack-first -Wl,--initial-memory=41943040]
    self.link_flags = Dir[File.join(SDK, "lib/*.a")].sort +
                      %w[-ldl -lwasi-emulated-signal -lwasi-emulated-getpid -lwasi-emulated-process-clocks -lpthread -lm]
    self.exports = %w[malloc free]
    self.extension = "pygments"
    self.loader_dir = "lib_dewasm"
    self.converted_name = "pygments_wasm"
  end

  def gemspec(spec)
    spec.require_paths = [loader_dir, "lib"]
  end

  def sdk_stamp = "#{SDK}.src-sha256"

  # The stamp covers the C host, the recipe, and the SDK build.
  def source_digest
    inputs = [self.class.source_path, HOST_SOURCE].map { |f| File.read(f) }
    inputs << File.read(sdk_stamp) if File.exist?(sdk_stamp)
    Digest::SHA256.hexdigest(inputs.join)[0, 16]
  end

  def before_compile
    unless File.exist?(File.join(SDK, "lib/libpython3.14.a")) && File.exist?(sdk_stamp)
      raise DewasmCExt::Compiler::Error, "#{SDK} is missing: #{SDK_HINT}"
    end
    builder.say "copying the Python standard library into the gem"
    FileUtils.cp_r(File.join(SDK, "lib", PYTHON), File.join(builder.gem_dir, PYTHON))
  end

  # Wizer calls `pyg_init` and writes the memory it leaves into a new module.
  # The gem directory is `/gem` here and at run time, so the paths CPython remembers hold.
  def after_compile(wasm)
    pre = wasm.sub(/\.wasm\z/, "-pre.wasm")
    builder.say "pre-initializing with Wizer (CPython boots and imports Pygments once)"
    DewasmCExt::Compiler.run(
      [ENV.fetch("WIZER", "wizer"), "--allow-wasi", "--init-func", "pyg_init", "--wasm-bulk-memory", "true",
       "--mapdir", "/gem::#{builder.gem_dir}", "-o", pre, wasm],
      log: builder.build_log
    )
    pre
  end

  # `Pygments::Popen` with `mentos` calling the reactor in this process.
  # One interpreter serves every `Popen` (the gem makes one per thread), under one lock.
  def loader(from:)
    original = File.join(builder.gem_dir, "lib/pygments.rb")
    converted = File.join(File.dirname(builder.loader_path), builder.converted_name)
    <<~RUBY
      # Generated by DewasmCExt: the Python process of pygments.rb, as a CPython converted to Ruby.
      # The gem's own `pygments.rb` is loaded first; `Popen#mentos` is the one method replaced.
      require_relative #{relative(original, from).inspect}
      require_relative #{relative(converted, from).inspect}
      require "json"

      module Pygments
        class Popen
          GEM_DIR = File.expand_path("..", __dir__)

          class << self
            def dewasm_call(header, code)
              (@dewasm_lock ||= Mutex.new).synchronize do
                @dewasm_instance ||= ::#{module_name}.new({}, args: ["python"], env: {}, preopens: { "/gem" => GEM_DIR })
                instance = @dewasm_instance
                memory = instance.memory
                code ||= ""
                header_ptr = instance.invoke("malloc", header.bytesize)
                code_ptr = instance.invoke("malloc", code.bytesize + 1)
                memory.buffer.set_string(header, header_ptr, header.bytesize, 0)
                memory.buffer.set_string(code, code_ptr, code.bytesize, 0) unless code.empty?
                pointer = instance.invoke("pyg_mentos", header_ptr, header.bytesize, code_ptr, code.bytesize)
                instance.invoke("free", header_ptr)
                instance.invoke("free", code_ptr)
                result = memory.buffer.get_string(pointer, instance.invoke("pyg_result_length"))
                result.force_encoding(Encoding::UTF_8)
                raise MentosError, result if instance.invoke("pyg_result_error") == 1

                result
              end
            end
          end

          def start(*) = nil
          def stop(*) = nil
          def alive? = true

          def mentos(method, args = [], kwargs = {}, code = nil)
            kwargs = kwargs.merge("bytes" => code.nil? ? 0 : code.bytesize)
            header = JSON.generate(method: method, args: args, kwargs: kwargs)
            return_result(Popen.dewasm_call(header, code), method)
          end
        end
      end
    RUBY
  end
end
