# frozen_string_literal: true

require "digest"
require "pathname"

module DewasmCExt
  class Recipe
    class << self
      def registry = (@registry ||= {})

      def register(gem_name, &block)
        source_path = caller_locations(1, 1).first.path
        registry[gem_name] = Class.new(self, &block).tap do |klass|
          klass.gem_name = gem_name
          klass.source_path = source_path
        end
      end

      def for(gem_name)
        registry.fetch(gem_name) do
          raise ArgumentError, "no recipe for #{gem_name}: add #{File.join(__dir__, 'recipes', "#{gem_name.tr('-', '_')}.rb")}"
        end
      end

      attr_accessor :gem_name, :source_path

      def checksums = (@checksums ||= {})
      def checksum(version, sha256) = checksums[version] = sha256

      def setting(name, default = nil)
        define_method(name) { instance_variable_defined?("@#{name}") ? instance_variable_get("@#{name}") : default }
        define_method("#{name}=") { |value| instance_variable_set("@#{name}", value) }
      end
    end

    setting :sources, []
    setting :include_dirs, []
    setting :defines, {}
    setting :cflags, []
    setting :init
    setting :extension
    setting :runtime_options, ""
    setting :support, true
    setting :exports, []
    setting :link_flags, []
    setting :loader_dir, "lib"
    setting :converted_name

    attr_reader :builder

    def initialize(builder)
      @builder = builder
      configure
    end

    def configure; end

    def before_compile; end

    def after_compile(wasm) = wasm

    def gemspec(spec); end

    def loader(from:)
      runtime = File.expand_path("../dewasm_cext.rb", __dir__)
      converted = File.join(File.dirname(builder.loader_path), builder.converted_name)
      <<~RUBY
        # Generated by DewasmCExt: the converted extension in place of the native one.
        require_relative #{relative(runtime, from).inspect}
        require_relative #{relative(converted, from).inspect}
        DewasmCExt::Runtime.new(#{module_name}, #{init_symbol.inspect}#{runtime_options})
      RUBY
    end

    def relative(path, from) = Pathname.new(path).relative_path_from(Pathname.new(from)).to_s

    def gem_name = self.class.gem_name
    def name = gem_name
    def module_name = "#{gem_name.split(/[^a-z0-9]/i).map(&:capitalize).join}Ext"
    def init_symbol = init || "Init_#{File.basename(extension)}"

    def source_digest = Digest::SHA256.file(self.class.source_path).hexdigest[0, 16]
  end
end
